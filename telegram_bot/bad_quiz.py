"""Квиз «Подобрать БАД» — выбор целей и подбор рекомендаций."""

from __future__ import annotations

GOALS = {
    1: "Улучшить кожу, волосы и ногти",
    2: "Снять отёки и тяжесть",
    3: "Снизить вес",
    4: "Улучшить концентрацию и память",
    5: "Энергия и бодрость",
    6: "Снизить стресс",
    7: "Поддержать суставы и подвижность",
}

# Простые рекомендации-заглушки (можно заменить на реальный каталог)
RECIPES: dict[int, list[str]] = {
    1: ["Коллагеновый комплекс", "Омега-3", "Биотин"],
    2: ["Магний + калий", "Комплекс для лимфы", "Водно-солевой баланс"],
    3: ["Метаболик-поддержка", "Клетчатка", "L-карнитин"],
    4: ["Омега-3", "Комплекс для мозга", "Витамины группы B"],
    5: ["Женьшень / адаптогены", "Витамин D", "Магний"],
    6: ["Магний глицинат", "Ашваганда", "Комплекс для нервной системы"],
    7: ["Коллаген + MSM", "Хондроитин/глюкозамин", "Витамин D + K2"],
}

INTRO = (
    "О, ты здесь! Я почти как врач — только без халата, диплома и занудства 🙂\n\n"
    "Если узнаёшь себя:\n"
    "• просыпаешься уже усталым(ой)\n"
    "• кожа и нервы «шалят»\n"
    "• волосы просят помощи\n"
    "• энергии едва хватает до обеда\n\n"
    "Давай подберём БАДы под твои цели. Это короткий тест — пара кликов."
)

ASK = (
    "Выбери до <b>3 целей</b>, которые важны сейчас:\n\n"
    + "\n".join(f"{n}. {title}" for n, title in GOALS.items())
    + "\n\nОтправь номера через запятую (например: <code>1,3,5</code>)\n"
    "или нажми готовую комбинацию ниже 👇"
)


def parse_goals(text: str) -> list[int] | None:
    raw = text.replace(" ", "")
    if not raw:
        return None
    parts = raw.split(",")
    nums: list[int] = []
    for p in parts:
        if not p.isdigit():
            return None
        n = int(p)
        if n not in GOALS or n in nums:
            return None
        nums.append(n)
    if not nums or len(nums) > 3:
        return None
    return nums


def build_result(goals: list[int]) -> str:
    lines = ["🧪 <b>Твой персональный подбор</b>\n"]
    seen: list[str] = []
    for g in goals:
        lines.append(f"<b>{g}. {GOALS[g]}</b>")
        for item in RECIPES.get(g, []):
            if item not in seen:
                seen.append(item)
                lines.append(f"  • {item}")
        lines.append("")
    lines.append(
        "Это ориентир для старта. Перед приёмом любых БАД "
        "лучше проконсультироваться со специалистом.\n"
        "Каталог и детали — в разделе «🛍 ПРОДУКТ»."
    )
    return "\n".join(lines)
