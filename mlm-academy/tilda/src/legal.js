  function assertLegalPublishReady() {
    if (!OPERATOR.fullName || !OPERATOR.email || !OPERATOR.phone || !OPERATOR.inn) {
      return { ok: false, reason: 'operator_incomplete' };
    }
    if (!api.isPersonInn(OPERATOR.inn)) {
      return { ok: false, reason: 'invalid_inn' };
    }
    var blob = allDocsBlob();
    var banned = ['Бор' + 'исенко', 'Бале' + 'шенко', '532000' + '135580', '1071@savv' + '.tech'];
    for (var b = 0; b < banned.length; b += 1) {
      if (blob.indexOf(banned[b]) !== -1) {
        return { ok: false, reason: 'forbidden_or_placeholder' };
      }
    }
    if (/\{\{|LEGAL_PLACEHOLDER|ЗАПОЛНИТЬ ВЛАДЕЛЬЦУ/.test(blob)) {
      return { ok: false, reason: 'forbidden_or_placeholder' };
    }
    if (/\b\d{20}\b/.test(blob) || /БИК\s*\d{9}/.test(blob) || /корр\.?\s*сч/i.test(blob)) {
      return { ok: false, reason: 'bank_details_in_public' };
    }
    return { ok: true, inn: OPERATOR.inn };
  }

